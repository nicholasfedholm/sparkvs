r"""Generates Table.g.cs (marker ids, embedded target table, simple span patch methods) from targets.json.
Run: python -I gen_table.py   (inputs: ..\..\..\..\sparkload-build\targets\targets.json). No em dashes in output."""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
TJ = os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "sparkload-build", "targets", "targets.json"))

MARKERS = [
    "client.boot.main", "client.boot.screenmanager",
    "client.boot.stage1", "client.boot.stage2", "client.boot.stage3", "client.boot.stage4", "client.boot.stage5",
    "server.launch", "server.phase", "mod.phase", "server.blocklist.wait", "server.blocklist.set",
    "server.remap.blocks", "server.remap.items", "server.save.load", "server.spawn.pregen",
    "column.pass", "column.load",
    "client.assets.handle", "client.assets.finish",
    "client.shapes.block", "client.shapes.item", "client.shapes.entity",
    "client.atlas.A", "client.atlas.B", "client.atlas.C",
    "client.handbook", "client.finalize.handle", "client.finalize.trigger", "frame",
    "client.boot.start",   # extra (ClientProgram.Start), not in SPEC list
]
MID = {n: i + 1 for i, n in enumerate(MARKERS)}

# target id -> (markers, pre, post)  ; pre/post None = generated simple span
SPECIAL = {
    "SRV_EnterRunPhase": ("Phase_Pre", "Phase_Post"),
    "ML_TryRunModPhase": ("ModPhase_Pre", "ModPhase_Post"),
    "SSMH_OnLoadAssets": ("Blocklist_Pre", None),
    "ML_LoadMods": (None, None),
    "SSSC_PopulateChunk": ("ColPass_Pre", "ColPass_Post"),
    "SSSC_LoadOrGenColumn": ("ColLoad_Pre", "ColLoad_Post"),
    "CEAPI_TriggerLevelFinalize": ("Fin_Pre", "Fin_Post"),
    "CM_MainGameLoop": ("Frame_Pre", "Frame_Post"),
}
SPECIAL["ML_LoadMods"] = ("BlocklistEnd_Pre", None)

MAP = {
    "CP_Main": ["client.boot.main"], "CP_Start": ["client.boot.start"], "SM_Start": ["client.boot.screenmanager"],
    "SM_Init1": ["client.boot.stage1"], "SM_Init2": ["client.boot.stage2"], "SM_Init3": ["client.boot.stage3"],
    "SM_Init4": ["client.boot.stage4"], "SM_Init5": ["client.boot.stage5"],
    "SRV_EnterRunPhase": ["server.phase"], "SRV_Launch": ["server.launch"],
    "ML_TryRunModPhase": ["mod.phase"],
    "SSMH_OnLoadAssets": ["server.blocklist.wait", "server.blocklist.set"],
    "ML_LoadMods": ["server.blocklist.wait"],
    "SSBIR_RemapBlocks": ["server.remap.blocks"], "SSIIR_RemapItems": ["server.remap.items"],
    "SSLS_LoadSaveGame": ["server.save.load"], "SSSC_InitWorldgen": ["server.spawn.pregen"],
    "SSSC_PopulateChunk": ["column.pass"], "SSSC_LoadOrGenColumn": ["column.load"],
    "CSS_HandleServerAssets": ["client.assets.handle"], "CSS_FinishAssetLoading": ["client.assets.finish"],
    "CSS_HandleLevelFinalize": ["client.finalize.handle"],
    "STM_LoadBlockShapes": ["client.shapes.block"], "STM_LoadItemShapes": ["client.shapes.item"],
    "STM_LoadEntityShapes": ["client.shapes.entity"],
    "TAM_StageA": ["client.atlas.A"], "TAM_StageB": ["client.atlas.B"], "TAM_StageC": ["client.atlas.C"],
    "SH_EventLevelFinalize": ["client.handbook"],
    "CEAPI_TriggerLevelFinalize": ["client.finalize.trigger", "frame"],
    "CM_MainGameLoop": ["frame"],
}
SPECIAL_MARKERS = {"server.phase", "mod.phase", "server.blocklist.wait", "server.blocklist.set", "column.pass",
                   "column.load", "frame", "client.finalize.trigger"}

def pascal(n):
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[.]", n))

rows = json.load(open(TJ, encoding="utf-8"))
byid = {r["marker"]: r for r in rows}
# add ML_LoadMods (2-param overload), verified with sigdump on stock and Optimum VintagestoryLib (ilLen 709 both)
byid["ML_LoadMods"] = {
    "marker": "ML_LoadMods", "assembly": "VintagestoryLib", "type": "Vintagestory.Common.ModLoader",
    "method": "LoadMods", "isStatic": False, "returnType": "System.Void",
    "params": [{"type": "System.Collections.Generic.List`1<Vintagestory.Common.ModContainer>"},
               {"type": "System.Collections.Generic.IEnumerable`1<System.String>"}],
    "optimumExtraOverloads": [],
}
order = [r["marker"] for r in rows]
order.insert(order.index("SSMH_OnLoadAssets") + 1, "ML_LoadMods")

def cs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = []
out.append("// <auto-generated> by gen_table.py from targets.json (+ ML_LoadMods). Do not edit. </auto-generated>")
out.append("using System;")
out.append("using System.Diagnostics;")
out.append("using System.Threading;")
out.append("")
out.append("namespace SparkLoad.Hook")
out.append("{")
out.append("    internal static class Mk")
out.append("    {")
for n in MARKERS:
    out.append("        public const int %s = %d;" % (pascal(n), MID[n]))
out.append("        public const int Count = %d;" % len(MARKERS))
out.append("        public static readonly string[] Names = new string[] { null, " + ", ".join(cs(n) for n in MARKERS) + " };")
out.append("    }")
out.append("")
out.append("    internal static class TargetTable")
out.append("    {")
out.append("        public static readonly TargetRow[] Rows = new TargetRow[]")
out.append("        {")
for tid in order:
    r = byid[tid]
    marks = MAP[tid]
    variants = [r["returnType"]] + [o["returnType"] for o in r.get("optimumExtraOverloads", [])]
    if tid in SPECIAL:
        pre, post = SPECIAL[tid]
    else:
        pre, post = "Span_%d_Pre" % MID[marks[0]], "Span_%d_Post" % MID[marks[0]]
    out.append("            new TargetRow(%s, new string[] { %s }, %s, %s, %s, %s, new string[] { %s }, new string[] { %s }, %s, %s)," % (
        cs(tid), ", ".join(cs(m) for m in marks), cs(r["assembly"]), cs(r["type"]), cs(r["method"]),
        "true" if r["isStatic"] else "false", ", ".join(cs(v) for v in variants),
        ", ".join(cs(p["type"]) for p in r["params"]),
        cs(pre) if pre else "null", cs(post) if post else "null"))
out.append("        };")
out.append("    }")
out.append("")
out.append("    internal static partial class Patches")
out.append("    {")
for n in MARKERS:
    if n in SPECIAL_MARKERS:
        continue
    i = MID[n]
    out.append("        public static void Span_%d_Pre()" % i)
    out.append("        {")
    out.append("            try { long q = Stopwatch.GetTimestamp(); if (!Core.On[%d]) return; Interlocked.Increment(ref Core.Hits[%d]); Emit.Begin(%d, q, 0, 0, 0, null); }" % (i, i, i))
    out.append("            catch { Core.Fault(); }")
    out.append("        }")
    out.append("        public static void Span_%d_Post()" % i)
    out.append("        {")
    out.append("            try { long q = Stopwatch.GetTimestamp(); if (!Core.On[%d]) return; Emit.End(%d, q, 0, 0, 0, null); }" % (i, i))
    out.append("            catch { Core.Fault(); }")
    out.append("        }")
out.append("    }")
out.append("}")
text = "\n".join(out) + "\n"
assert chr(0x2014) not in text and chr(0x2013) not in text
open(os.path.join(HERE, "Table.g.cs"), "w", encoding="utf-8", newline="\n").write(text)
print("rows", len(order), "markers", len(MARKERS))
for tid in order:
    r = byid[tid]
    print(" | ".join([",".join(MAP[tid]), r["type"] + "." + r["method"], "+".join(v.split(".")[-1] for v in [r["returnType"]] + [o["returnType"] for o in r.get("optimumExtraOverloads", [])])]))
